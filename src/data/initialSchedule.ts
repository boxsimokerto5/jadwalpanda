/**
 * Helper untuk mendapatkan inisial huruf kecil petugas (misal 'ew' untuk Eko Wahyudi)
 */
export function getStaffInitials(staff: Staff | string | { name: string; initials?: string }): string {
  if (typeof staff === 'object' && staff.initials) {
    return staff.initials.toLowerCase();
  }
  const rawName = typeof staff === 'string' ? staff : (staff ? staff.name : '');
  if (!rawName) return '';

  const cleaned = rawName.replace(/['’.]/g, ' ').trim();
  const words = cleaned.split(/\s+/).filter((w) => w.length > 0 && !['s.pd', 'm.pd', 'i', 'y'].includes(w.toLowerCase()));

  if (words.length === 1) {
    return words[0].substring(0, 2).toLowerCase();
  }
  return words.map((w) => w[0].toLowerCase()).slice(0, 3).join('');
}

