export const getInitialAugust2026Days = (totalDays = 31): Record<number, Record<number, ShiftCode>> => {
  const baseDays: Record<number, Record<number, ShiftCode>> = {};
  for (let d = 1; d <= totalDays; d++) {
    baseDays[d] = {};
  }
  return baseDays;
};

